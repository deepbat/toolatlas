import assert from 'node:assert/strict';
import { searchTools, suggestQuery } from '../src/lib/search';
import { TOOLS, TOOL_MAP } from '../src/lib/catalog';

const ids = (query: string) => searchTools(query).map((tool) => tool.id);
assert.equal(searchTools('').length, TOOLS.length, 'empty query returns complete catalogue');
assert.ok(ids('imge').some((id) => TOOL_MAP[id]?.category === 'image'), 'one-character typo finds image tools');
assert.ok(ids('photo').includes('passport-photo'), 'photo finds the passport photo maker');
assert.ok(ids('pdf redact').includes('pdf-redaction-verify'), 'multi-term search finds the PDF redactor');
assert.ok(ids('tax').includes('income-tax-india'), 'tax finds the India income tax calculator');
assert.ok(ids('spreadsheet').includes('file-converter'), 'spreadsheet synonym finds the file converter');
assert.equal(ids('zzqvxx').length, 0, 'unrelated query has no false positives');
assert.ok(ids('vetan').length > 0, 'Hindi word for salary finds finance tools');
assert.equal(suggestQuery('pasprt'), 'passport', 'two-letter typo gets a did-you-mean');
assert.equal(suggestQuery('zzqvxx'), null, 'nonsense gets no suggestion');
assert.equal(suggestQuery('passport'), null, 'a query with results gets no suggestion');
assert.ok(ids('वेतन').length > 0, 'Hindi script finds salary tools');
assert.ok(ids('ਤਨਖਾਹ').length > 0, 'Punjabi script finds salary tools');
assert.ok(ids('पीडीएफ').some((id) => TOOL_MAP[id]?.category === 'pdf'), 'Hindi PDF finds PDF tools');
console.log('Search regression checks passed.');
