export function Icon({
  name,
  className,
  strokeWidth = 1.75,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = ICONS[name] ?? Compass;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}
